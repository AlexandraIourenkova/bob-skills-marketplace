"""The project lock file: ``.bob/skills.lock`` (or ``~/.bob/skills.lock``).

TOML, one ``[[pack]]`` table per installed pack, with a ``[pack.skillDigests]``
sub-table holding the digest of every installed skill folder. The guard hook
compares the folder on disk against these digests before Bob activates a skill.
"""

from __future__ import annotations

import json
import tomllib
from pathlib import Path

LOCK_NAME = "skills.lock"
LOCK_VERSION = 1

SCALAR_ORDER = ["name", "version", "vendor", "digest", "installed", "registry", "registryCommit"]
LIST_ORDER = ["networkAllow", "skills", "mcpServers", "rules", "commands", "modes", "policyAccepted"]


def lock_path(bob_dir: Path) -> Path:
    return Path(bob_dir) / LOCK_NAME


def read_lock(bob_dir: Path) -> dict:
    path = lock_path(bob_dir)
    if not path.is_file():
        return {"version": LOCK_VERSION, "pack": []}
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    data.setdefault("version", LOCK_VERSION)
    data.setdefault("pack", [])
    return data


def _toml_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        return "[" + ", ".join(_toml_value(v) for v in value) + "]"
    raise TypeError(f"unsupported lock value: {value!r}")


def write_lock(bob_dir: Path, lock: dict) -> Path:
    path = lock_path(bob_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by bob-skills. Do not edit by hand; use `bob-skills add|remove|trust`.",
        f"version = {lock.get('version', LOCK_VERSION)}",
        "",
    ]
    for entry in sorted(lock.get("pack", []), key=lambda e: e.get("name", "")):
        lines.append("[[pack]]")
        for key in SCALAR_ORDER:
            if key in entry and entry[key] is not None:
                lines.append(f"{key} = {_toml_value(entry[key])}")
        for key in LIST_ORDER:
            if key in entry:
                lines.append(f"{key} = {_toml_value(list(entry[key]))}")
        digests = entry.get("skillDigests") or {}
        if digests:
            lines.append("")
            lines.append("[pack.skillDigests]")
            for skill in sorted(digests):
                lines.append(f"{json.dumps(skill)} = {_toml_value(digests[skill])}")
        lines.append("")
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    return path


def get_entry(lock: dict, name: str) -> dict | None:
    for entry in lock.get("pack", []):
        if entry.get("name") == name:
            return entry
    return None


def set_entry(lock: dict, entry: dict) -> None:
    lock["pack"] = [e for e in lock.get("pack", []) if e.get("name") != entry["name"]] + [entry]


def remove_entry(lock: dict, name: str) -> bool:
    before = len(lock.get("pack", []))
    lock["pack"] = [e for e in lock.get("pack", []) if e.get("name") != name]
    return len(lock["pack"]) != before


def entry_for_skill(lock: dict, skill: str) -> dict | None:
    for entry in lock.get("pack", []):
        if skill in entry.get("skills", []):
            return entry
    return None
